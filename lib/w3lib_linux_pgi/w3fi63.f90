   !  ------------------- BYTE 21-23   LONGITUDE OF LAST GRID POINT
   !
   CALL GBYTE (MSGA,KGDS(8),KPTR(8),24)
   KPTR(8)  = KPTR(8) + 24
   IF (IAND(KGDS(8),8388608).NE.0) THEN
       KGDS(8)  =  - IAND(KGDS(8),8388607)
   END IF
