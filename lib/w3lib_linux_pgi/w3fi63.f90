   KPTR(8)  = KPTR(8) + 24
   IF (IAND(KGDS(14),8388608).NE.0) THEN
       KGDS(14)  =  - IAND(KGDS(14),8388607)
   END IF
   !
   !  ------------------- BYTE 38-40   LONGITUDE OF SOUTHERN POLE
   !
