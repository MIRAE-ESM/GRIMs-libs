   KPTR(8)  = KPTR(8) + 24
   IF (IAND(KGDS(13),8388608).NE.0) THEN
       KGDS(13)  =  - IAND(KGDS(13),8388607)
   END IF
   !
   !  ------------------- BYTE 35-37   LATITUDE OF SOUTHERN POLE
   !
