!     ELSE IF (KGDS(1).EQ.70) THEN
!     ELSE IF (KGDS(1).EQ.80) THEN
   ELSE IF (KGDS(1).EQ.201.OR.KGDS(1).EQ.202) THEN
       GO TO 1000
   ELSE
!                      MARK AS GDS/ UNKNOWN DATA REPRESENTATION TYPE
       KRET     = 4
       RETURN
   END IF
