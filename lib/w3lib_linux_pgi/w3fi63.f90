           DATA(I) = DATA(LASTP)
 4012     CONTINUE
   ELSE
       CALL GBYTES (MSGA,KSAVE,KPTR(8),KBITS,0,KNR)
       II    = 1
       KENTRY = KPTR(10)
       DO 500 I = 1, KENTRY
           IF (KBMS(I)) THEN
               DATA(I) = (REFNCE + FLOAT(KSAVE(II)) * SCALE) * SCAL10
