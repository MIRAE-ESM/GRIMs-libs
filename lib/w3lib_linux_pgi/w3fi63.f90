   SAVE
   KRET    = 0
   !
   ! PROCESS GRID DEFINITION SECTION (IF PRESENT)
   ! MAKE SURE BIT POINTER IS PROPERLY SET
   !
   KPTR(8)  = KPTR(9) + (KPTR(2)*8) + (KPTR(3)*8) + 24
   NSAVE    = KPTR(8) - 24
