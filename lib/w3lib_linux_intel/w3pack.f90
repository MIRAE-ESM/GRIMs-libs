!     PROCESS LAT/LON GRID TYPES OR GAUSSIAN GRID OR ARAKAWA
!     SEMI-STAGGERED OF FILLED E-GRIDS
!
   IF (IGDS(3).EQ.0.OR.IGDS(3).EQ.4.OR.                                        &
       IGDS(3).EQ.200.OR.IGDS(3).EQ.201) THEN
