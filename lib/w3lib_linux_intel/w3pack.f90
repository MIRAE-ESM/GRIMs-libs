     ENDIF
     GDS(11) = CHAR(MOD(LATO/65536,256))
     GDS(12) = CHAR(MOD(LATO/  256,256))
     GDS(13) = CHAR(MOD(LATO      ,256))
     LONO = IGDS(7)
     IF (LONO .LT. 0) THEN
       LONO = -LONO
       LONO = IOR(LONO,8388608)
